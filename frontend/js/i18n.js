export const LANGUAGE_KEY = 'herbalStore.language';

export function getLanguage() {
  try { return localStorage.getItem(LANGUAGE_KEY) === 'ru' ? 'ru' : 'uz'; }
  catch { return 'uz'; }
}

export function setLanguage(language) {
  if (!['uz', 'ru'].includes(language)) throw new TypeError('Unsupported language.');
  localStorage.setItem(LANGUAGE_KEY, language);
}

export function t(text) {
  return getLanguage() === 'ru' ? russian[text] ?? text : text;
}

export function resultCount(count, category = false) {
  if (getLanguage() === 'uz') return `${count} ta ${category ? 'kategoriya' : 'mahsulot'}`;
  const last = count % 10;
  const teen = count % 100 >= 11 && count % 100 <= 14;
  const forms = category ? ['категория', 'категории', 'категорий'] : ['товар', 'товара', 'товаров'];
  return `${count} ${forms[teen ? 2 : last === 1 ? 0 : last >= 2 && last <= 4 ? 1 : 2]}`;
}

// Run once, before rendering API content. Exact lookups never translate catalog text.
export function localizeInterface(root = document) {
  document.documentElement.lang = getLanguage();
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest('script, style, [data-brand-name]')) continue;
    const source = node.textContent.trim();
    if (Object.hasOwn(russian, source)) node.textContent = node.textContent.replace(source, t(source));
  }
  root.querySelectorAll('[aria-label]').forEach((node) => {
    node.setAttribute('aria-label', t(node.getAttribute('aria-label')));
  });
}
